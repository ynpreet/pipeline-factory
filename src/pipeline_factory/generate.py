def _deidentify(value: str) -> str:
    """One-way hash of a PII value. The raw value is never retained."""
    return hashlib.sha256(f"{{SALT}}:{{value}}".encode()).hexdigest()[:16]


def _coerce(value, kind):
    if value is None or value == "":
        return None
    if kind == "integer":
        return int(value)
    if kind == "float":
        return float(value)
    if kind == "boolean":
        return str(value).lower() in ("1", "true", "yes")
    return str(value)


def _in_range(value, lo, hi):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return False
    return lo <= v <= hi


def _derive(expression, row):
    """Evaluate a derive expression against the row.

    Only the row's own fields are visible; no builtins are exposed.
    """
    safe = {{k: row.get(k) for k in row}}
    return eval(expression, {{"__builtins__": {{}}}}, safe)


def _coerce_row(row):
    """Coerce typed columns to Python values (best effort; failures stay
    as raw strings so validation can quarantine the row)."""
    for name, kind in TYPES.items():
        if name in PII_FIELDS or kind == "string":
            continue
        try:
            row[name] = _coerce(row.get(name), kind)
        except (TypeError, ValueError):
            pass
    return row


