def _readme_source(spec: PipelineSpec) -> str:
    lines = [
        f"# Generated pipeline: {spec.name} (v{spec.version})",
        "",
        spec.description or "No description.",
        "",
        "Generated by Pipeline Factory from the pipeline spec. Do not edit by hand.",
        "",
        "## Run",
        "",
        "```bash",
        f"python pipeline_{spec.name}.py <input.csv>",
        "```",
        "",
        "## Tests",
        "",
        "```bash",
        "pytest -q",
        "```",
        "",
        "## Spec summary",
        "",
        f"- Source: `{spec.source.path}` ({len(spec.source.schema)} columns, "
        f"PII: {', '.join(spec.pii_fields()) or 'none'})",
        f"- Transforms: {', '.join(t.kind for t in spec.transforms) or 'none'}",
        f"- Quality gates: {', '.join(g.kind for g in spec.quality_gates) or 'none'}",
        f"- Destination: `{spec.destination.path}`; "
        f"quarantine: `{spec.destination.quarantine_path}`",
        "",
    ]
    return "\n".join(lines)
