"""Code generation: turn a validated PipelineSpec into working code.

Output (under <out_dir>/<name>/):
  pipeline_<name>.py   self-contained stdlib-only pipeline
  test_pipeline_<name>.py  pytest tests for the generated pipeline
  README.md            what was generated and how to run it

The generated pipeline is real, runnable code: it reads the source CSV,
applies transforms in order (deidentify -> validate -> derive), writes a
governed output and a quarantine file for rejected rows, and appends an
audit record for every run.
"""

